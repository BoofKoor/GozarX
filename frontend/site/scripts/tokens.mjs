// Writes styles/tokens.css — the four theme blocks — from styles/tokens.mjs, the one definition of
// each colour token (C-58). `--check` (run by `npm run build`) fails instead when the file on disk
// is not what the source generates: a token edited in one place only is the bug this exists to end.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dark, light } from "../styles/tokens.mjs";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "styles", "tokens.css");
const onlyIn = [...Object.keys(light).filter((k) => !(k in dark)), ...Object.keys(dark).filter((k) => !(k in light))];
if (onlyIn.length) {
  console.error(`tokens: defined in one theme only: ${onlyIn.join(", ")}`);
  process.exit(1);
}
const body = (t) => Object.entries(t).map(([k, v]) => `--${k}:${v};`).join(" ");
const AUTO = '#app:not([data-theme="light"]):not([data-theme="dark"])';
const css = `/* GENERATED by scripts/tokens.mjs from styles/tokens.mjs — do not edit; run \`npm run tokens\`.
   Four blocks, one definition: no choice follows the device (the two auto blocks), and an explicit
   #app[data-theme] always wins. */
${AUTO}{ ${body(light)} }
@media (prefers-color-scheme: dark){ ${AUTO}{ ${body(dark)} } }
#app[data-theme="light"]{ ${body(light)} }
#app[data-theme="dark"]{ ${body(dark)} }
`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== css) {
    console.error("tokens: styles/tokens.css is stale — run `npm run tokens` and commit the result.");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, css);
  console.log(`tokens: wrote ${Object.keys(light).length} tokens × 4 blocks to styles/tokens.css`);
}
